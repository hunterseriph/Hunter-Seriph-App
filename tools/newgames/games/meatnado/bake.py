"""Bakes Meatnado Escape's backdrop and tornado art into 0-img.js (window.MNIMG + NB).

src/city-layer.png is Hunter's own city strip (transparent sky, the Cum Café on its own lot at the start, Ejaculand
with the carousel and clock tower at the end). The other src/*.png layers (sky, clouds, skyline, bricks, the
meatnado and its sausages) come from the first version of the game. Everything is stored lossless, and the city is
baked at 3x its on-screen height, because the old lossy, half-size drawing is what made the backdrop look crunchy.
Run: python3 bake.py  (then build the game with tools/newgames/build.py meatnado)
"""
import base64, io, json, os
import numpy as np
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); SRC = os.path.join(HERE, 'src')

def load(n, mode='RGBA'): return Image.open(os.path.join(SRC, n + '.png')).convert(mode)

CITY_H = 396  # baked at 3x its on-screen height (132), so phones draw it 1:1 and it stays sharp

def city():
    """Hunter's own city strip (src/city-layer.png, transparent, the café on its own lot, Ejaculand at the end)"""
    im = load('city-layer'); a = np.array(im)
    ys = np.where(a[..., 3].max(1) > 0)[0]; im = im.crop((0, 0, im.width, int(ys.max()) + 1))
    w = round(im.width * CITY_H / im.height)
    return im.convert('RGBa').resize((w, CITY_H), Image.LANCZOS).convert('RGBA')

def uri(im, lossless=True):
    b = io.BytesIO(); im.save(b, 'WEBP', lossless=lossless, quality=100, method=6)
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()

def main():
    c = city(); c.save(os.path.join(HERE, 'city-preview.png'))
    imgs = {'city': uri(c), 'sky': uri(load('sky', 'RGB')), 'clouds': uri(load('clouds')), 'skyline': uri(load('skyline')),
            'bricks': uri(load('bricks', 'RGB')), 'nado': uri(load('nado')), 'saus': uri(load('saus'))}
    nb = json.load(open(os.path.join(SRC, 'nb.json')))
    js = '/* generated by bake.py: the backdrop and tornado art */\nvar MNIMG = ' + json.dumps(imgs) + ';\nvar NB = ' + json.dumps(nb) + ';\n'
    open(os.path.join(HERE, '0-img.js'), 'w').write(js)
    print('city', c.size, '0-img.js', len(js) // 1024, 'KB')

if __name__ == '__main__': main()
