#!/usr/bin/env python3
"""Turns the Night City sky, clouds and far skyline (Hunter's own art, first made for the original Spermhog, kept in tools/spermhog/assets)
into 0-img.js (HOGIMG). The shops on the street are Load Legacy's own fac_ sprites (art.py USE) so the build can embed them. Run it if those pictures change."""
import base64, json, os
HERE = os.path.dirname(os.path.abspath(__file__)); A = os.path.join(HERE, '..', '..', '..', 'spermhog', 'assets')
out = {}
for k in ['sky', 'clouds', 'skyline']:
    out[k] = 'data:image/webp;base64,' + base64.b64encode(open(os.path.join(A, k + '.webp'), 'rb').read()).decode()
open(os.path.join(HERE, '0-img.js'), 'w').write('/* Night City backdrops (generated by bake.py) */\nvar HOGIMG = ' + json.dumps(out) + ';\n')
print('wrote 0-img.js', sum(len(v) for v in out.values()) // 1024, 'KB')
